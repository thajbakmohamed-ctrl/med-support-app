package com.app.med_support.model;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.persistence.*;
import jakarta.validation.constraints.Min;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;

@Entity
@Table(name = "donation_slot",
        check = {
                @CheckConstraint(name = "chk_donation_slot_capacity",
                        constraint = "capacity >= 1 AND reserved_count >= 0 AND reserved_count <= capacity"
                )
        }
)
@Getter
@Setter
public class DonationSlot {

    @Schema(description = "Unique donation slot ID generated automatically by the database.",
            example = "3",
            accessMode = Schema.AccessMode.READ_ONLY)

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;


    @Schema(description = "Hospital associated with this slot. " +
                    "Automatically assigned from the authenticated HOSPITAL_STAFF account.",
            accessMode = Schema.AccessMode.READ_ONLY)

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "hospital_id", nullable = false)
    private Hospital hospital;


    @Schema(description = "Date of the donation slot in YYYY-MM-DD format.",
            example = "2026-11-05",
            requiredMode = Schema.RequiredMode.REQUIRED)

    @Column(name = "slot_date", nullable = false)
    private LocalDate slotDate;


    @Schema(description = "Start time of the donation slot in HH:mm:ss format.",
            example = "09:00:00",
            requiredMode = Schema.RequiredMode.REQUIRED)

    @Column(name = "start_time", nullable = false)
    private LocalTime startTime;

    @Schema(description = "End time of the donation slot in HH:mm:ss format. Must be after the start time.",
            example = "12:00:00",
            requiredMode = Schema.RequiredMode.REQUIRED)
    @Column(name = "end_time", nullable = false)
    private LocalTime endTime;


    @Schema(description = "Maximum number of donation bookings allowed for this slot. " +
                    "Capacity must be at least 1 and cannot be reduced below the number of existing reservations.",
            example = "5",
            minimum = "1",
            requiredMode = Schema.RequiredMode.REQUIRED)

    @Min(value = 1, message = "Capacity must be at least 1")
    @Column(name = "capacity", nullable = false)
    private Integer capacity;


    @Schema(description = "Number of places already reserved. " +
                    "Automatically managed by the backend when bookings are created or cancelled. " +
                    "Must be between 0 and capacity.",
            example = "2",
            minimum = "0",
            accessMode = Schema.AccessMode.READ_ONLY)

    @Min(value = 0, message = "Reserved count cannot be negative")
    @Column(name = "reserved_count", nullable = false)
    private Integer reservedCount = 0;


    @Schema(description = "Current status of the donation slot. " +
                    "OPEN means the slot can accept bookings if capacity is available. " +
                    "CLOSED means the slot is not available for new bookings. " +
                    "The status is managed by the backend.",
            example = "OPEN",
            allowableValues = {"OPEN", "CLOSED"},
            accessMode = Schema.AccessMode.READ_ONLY)

    @Column(name = "status", nullable = false)
    private String status = "OPEN";


    @Schema(description = "Date and time when the slot was created. Automatically generated by the system.",
            example = "2026-10-24T10:30:00",
            accessMode = Schema.AccessMode.READ_ONLY)
    @CreationTimestamp
    @Column(name = "created_at", updatable = false)
    private LocalDateTime createdAt;


    @Schema(description = "Date and time when the slot was last updated. Automatically managed by the system.",
            example = "2026-10-24T11:00:00",
            accessMode = Schema.AccessMode.READ_ONLY)
    @UpdateTimestamp
    @Column(name = "updated_at")
    private LocalDateTime updatedAt;


}
