CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    email_verified BOOLEAN NOT NULL,
    verification_token VARCHAR(255),
    verification_token_expiry TIMESTAMP(6) WITHOUT TIME ZONE,
    profile_image VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    hospital_id BIGINT,
    password_reset_token VARCHAR(255),
    password_reset_token_expiry TIMESTAMP(6) WITHOUT TIME ZONE,
    cpr_document VARCHAR(255),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_phone UNIQUE (phone),
    -- Scalar cross-service ID; enforce the hospital existence checked by UserService.
    CONSTRAINT fk_users_hospital FOREIGN KEY (hospital_id)
        REFERENCES public.hospital (id) ON DELETE RESTRICT
);

CREATE INDEX ix_users_hospital ON public.users (hospital_id);
CREATE INDEX ix_users_verification_token ON public.users (verification_token)
    WHERE verification_token IS NOT NULL;
CREATE INDEX ix_users_password_reset_token ON public.users (password_reset_token)
    WHERE password_reset_token IS NOT NULL;

CREATE TABLE public.donor_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    blood_type VARCHAR(255) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(255) NOT NULL,
    weight_kg DOUBLE PRECISION NOT NULL,
    medical_conditions VARCHAR(255),
    medications VARCHAR(255),
    allergies VARCHAR(255),
    last_donation_date DATE,
    total_donations INTEGER NOT NULL DEFAULT 0,
    cpr_image VARCHAR(255) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    notes VARCHAR(255),
    created_at_donor_profile TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uq_donor_profile_user UNIQUE (user_id),
    CONSTRAINT fk_donor_profile_user FOREIGN KEY (user_id)
        REFERENCES public.users (id) ON DELETE RESTRICT,
    -- Source: DonorProfileRequest @Positive and DonorProfileService validation.
    CONSTRAINT ck_donor_profile_weight CHECK (weight_kg > 0)
);

