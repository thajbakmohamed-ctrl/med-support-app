BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '120s';

DO $$
BEGIN
    IF current_database() <> 'med_support' THEN
        RAISE EXCEPTION 'Wrong database: %. Expected med_support.', current_database();
    END IF;
    IF to_regclass('public.donor_profile') IS NULL
       OR to_regclass('public.blood_request') IS NULL
       OR to_regclass('public.donation_slot') IS NULL THEN
        RAISE EXCEPTION 'Missing S001/S002/S003 prerequisites.';
    END IF;
END
$$;

CREATE TABLE public.donation_booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_profile_id BIGINT NOT NULL,
    blood_request_id BIGINT NOT NULL,
    donation_slot_id BIGINT NOT NULL,
    donation_booking_date DATE NOT NULL,
    donation_booking_time TIME(6) WITHOUT TIME ZONE NOT NULL,
    donation_booking_status VARCHAR(255) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_donation_booking_donor FOREIGN KEY (donor_profile_id)
        REFERENCES public.donor_profile (id) ON DELETE RESTRICT,
    CONSTRAINT fk_donation_booking_request FOREIGN KEY (blood_request_id)
        REFERENCES public.blood_request (id) ON DELETE RESTRICT,
    CONSTRAINT fk_donation_booking_slot FOREIGN KEY (donation_slot_id)
        REFERENCES public.donation_slot (id) ON DELETE RESTRICT
);

-- Preserve the three indexes declared by DonationBooking.
CREATE INDEX idx_booking_donor ON public.donation_booking (donor_profile_id);
CREATE INDEX idx_booking_request ON public.donation_booking (blood_request_id);
CREATE INDEX idx_booking_slot ON public.donation_booking (donation_slot_id);
CREATE INDEX ix_booking_request_status
    ON public.donation_booking (blood_request_id, donation_booking_status);
CREATE INDEX ix_booking_donor_date_time
    ON public.donation_booking (donor_profile_id, donation_booking_date, donation_booking_time);

-- Duplicate prevention/capacity updates remain coordinated by the existing donor
-- advisory lock, request/slot row locks and service validation. No invented unique
-- booking/type rule or trigger; cross-table hospital/time equality stays in the service.
CREATE TABLE public.booking_outbox_events (
    event_id UUID PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    recipient_email VARCHAR(255) NOT NULL,
    notification_type VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    published_at TIMESTAMP(6) WITHOUT TIME ZONE,
    -- Retain events: never cascade-delete them when a booking is removed.
    CONSTRAINT fk_booking_outbox_booking FOREIGN KEY (booking_id)
        REFERENCES public.donation_booking (id) ON DELETE RESTRICT
);

CREATE INDEX idx_booking_outbox_status
    ON public.booking_outbox_events (status, created_at);
CREATE INDEX ix_booking_outbox_pending_order
    ON public.booking_outbox_events (created_at, event_id) WHERE status = 'PENDING';
CREATE INDEX ix_booking_outbox_booking ON public.booking_outbox_events (booking_id);

-- event_id is generated in Java and retained across retries; no UUID extension needed.
-- Notification's asynchronous booking reference remains intentionally unconstrained
-- by an FK in its separately maintained V001; do not alter that migration here.
COMMIT;
