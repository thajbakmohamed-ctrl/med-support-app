CREATE TABLE public.blood_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL,
    blood_type VARCHAR(255) NOT NULL,
    units_needed INTEGER NOT NULL,
    urgency VARCHAR(255) NOT NULL,
    needed_date DATE NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'OPEN',
    description VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_blood_request_hospital FOREIGN KEY (hospital_id)
        REFERENCES public.hospital (id) ON DELETE RESTRICT,
    -- Source: BloodRequestRequest @Min(1).
    CONSTRAINT ck_blood_request_units CHECK (units_needed >= 1)
);

CREATE INDEX ix_blood_request_hospital ON public.blood_request (hospital_id);
CREATE INDEX ix_blood_request_status_type ON public.blood_request (status, blood_type);

CREATE TABLE public.donation_slot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL,
    slot_date DATE NOT NULL,
    start_time TIME(6) WITHOUT TIME ZONE NOT NULL,
    end_time TIME(6) WITHOUT TIME ZONE NOT NULL,
    capacity INTEGER NOT NULL,
    reserved_count INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(255) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_donation_slot_hospital FOREIGN KEY (hospital_id)
        REFERENCES public.hospital (id) ON DELETE RESTRICT,
    -- Exact invariant declared in DonationSlot's @CheckConstraint.
    CONSTRAINT chk_donation_slot_capacity
        CHECK (capacity >= 1 AND reserved_count >= 0 AND reserved_count <= capacity),
    -- Source: DonationSlotService.createSlot requires endTime.isAfter(startTime).
    CONSTRAINT ck_donation_slot_time CHECK (end_time > start_time)
);

CREATE INDEX ix_donation_slot_hospital_date_time
    ON public.donation_slot (hospital_id, slot_date, start_time, id);

-- Date eligibility is evaluated by application code, not moving CURRENT_DATE CHECKs.
COMMIT;
