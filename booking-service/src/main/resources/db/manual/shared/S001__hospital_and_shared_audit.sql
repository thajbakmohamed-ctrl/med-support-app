BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '120s';

DO $$
BEGIN
    IF current_database() <> 'med_support' THEN
        RAISE EXCEPTION 'Wrong database: %. Expected med_support.', current_database();
    END IF;
    IF current_setting('server_version_num')::integer < 150000 THEN
        RAISE EXCEPTION 'This migration requires PostgreSQL 15 or later.';
    END IF;
    -- Fail closed if any application table already exists in public.
    -- Catalog inspection only: no existing table is read or changed.
    IF EXISTS (
        SELECT 1 FROM pg_catalog.pg_class c
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
    ) THEN
        RAISE EXCEPTION 'Expected a fresh public schema; inspect existing tables and migration history.';
    END IF;
END
$$;

CREATE TABLE public.hospital (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uq_hospital_phone UNIQUE (phone)
);

-- The three AuditLog entities have identical column/type/nullability contracts.
-- Preserve nullable fields and default String length; no user FK for historical emails.
CREATE TABLE public.system_audit_logs (
    audit_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_action VARCHAR(255),
    performed_by_email VARCHAR(255),
    action_description VARCHAR(255),
    audit_created_at TIMESTAMP(6) WITHOUT TIME ZONE
);

COMMIT;
