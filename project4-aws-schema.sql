CREATE TABLE public.p4_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID,
    recipient_email VARCHAR(255) NOT NULL,
    notification_type VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'PENDING',
    booking_id BIGINT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    sent_at TIMESTAMP(6) WITHOUT TIME ZONE,
    retry_count INTEGER NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMP(6) WITHOUT TIME ZONE,
    processing_started_at TIMESTAMP(6) WITHOUT TIME ZONE,
    processing_token UUID,

    -- NULL event IDs remain valid for legacy-style Project 4 creation.
    -- PostgreSQL's default NULLS DISTINCT permits multiple such rows.
    CONSTRAINT uq_p4_notifications_event_id
        UNIQUE (event_id) NOT DEFERRABLE,

    CONSTRAINT ck_p4_notifications_status
        CHECK (status IN ('PENDING', 'PROCESSING', 'FAILED', 'SENT')),

    -- Counts all attempts, including the first, durably before SMTP.
    CONSTRAINT ck_p4_notifications_attempts
        CHECK (retry_count BETWEEN 0 AND 3),

    CONSTRAINT ck_p4_notifications_ownership
        CHECK (
            (
                status = 'PROCESSING'
                AND processing_token IS NOT NULL
                AND processing_started_at IS NOT NULL
                AND retry_count BETWEEN 1 AND 3
            )
            OR
            (
                status <> 'PROCESSING'
                AND processing_token IS NULL
                AND processing_started_at IS NULL
            )
        )
);

-- No booking/type uniqueness: distinct Kafka event IDs must stay independent.
-- No legacy-table ALTER, DROP, UPDATE, DELETE, TRUNCATE, or data-copy operations.

CREATE INDEX ix_p4_notifications_pending
    ON public.p4_notifications (created_at)
    WHERE status = 'PENDING' AND retry_count < 3;

CREATE INDEX ix_p4_notifications_retry
    ON public.p4_notifications (next_retry_at, created_at)
    WHERE status = 'FAILED' AND retry_count < 3;

CREATE INDEX ix_p4_notifications_processing
    ON public.p4_notifications (processing_started_at, id)
    WHERE status = 'PROCESSING';

CREATE INDEX ix_p4_notifications_booking
    ON public.p4_notifications (booking_id);

CREATE INDEX ix_p4_notifications_recipient
    ON public.p4_notifications (recipient_email, created_at DESC);

COMMIT;

